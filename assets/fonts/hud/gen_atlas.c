/* SPDX-License-Identifier: AGPL-3.0-only
 *
 * Offline atlas generator for compositor-drawn text (ADR 0071, ADR 0009: the
 * compositor has no font engine and must not grow one at runtime, so a face
 * is rasterised here, once, and the 8-bit coverage is checked in and compiled
 * in with `include_bytes!`). Proportional faces: every glyph carries its own
 * advance.
 *
 * Build:
 *
 *     cc -O2 -o gen_atlas gen_atlas.c $(pkg-config --cflags --libs freetype2) -lm
 *
 * One atlas per run:
 *
 *     gen_atlas --font F.ttf --px 13 --scale 1 --charset charset.txt --out title-1x.a8
 *               [--fallback G.ttf] [--embolden 0.35]
 *
 *   --font      primary face; every codepoint it carries is drawn from it.
 *   --fallback  a second face for codepoints the primary lacks (Onest has no
 *               Greek or maths; JetBrains Mono fills in). A codepoint in
 *               neither is a hard error: nothing is silently dropped.
 *   --px        em size in pixels at 1x. Advances are always measured at this
 *               size, so layout is the same whatever --scale rasterises at.
 *   --scale     raster scale (1 or 2): the glyph bitmaps are drawn at
 *               px * scale; the advance table is unchanged.
 *   --charset   cell order, one entry per line (# comments):
 *                 XXXX       one codepoint            (hex, no prefix)
 *                 XXXX-YYYY  an inclusive run
 *                 PPPP=B+M   a composed cell: base letter B with combining
 *                            mark M, drawn at private-use PPPP. The mark is
 *                            centred over the base's advance box and lifted
 *                            clear of a tall base.
 *   --embolden  extra stem width at 1x in pixels (default 0).
 *
 * File format "HUD3" (little endian):
 *   0..4        magic "HUD3"
 *   4           cell width   (pixels)
 *   5           cell height  (pixels)
 *   6           margin       (pixels left of the pen inside each cell)
 *   7           ascent       (pixels, baseline from the cell's top row)
 *   8..8+2N     N advances, u16, in 1/64 logical (1x) pixel, cell order
 *   8+2N..      N cells of cell_w*cell_h coverage bytes, row-major, top first
 * A glyph's pen is its cell's column `margin`; ink sits at `margin + left
 * bearing`. Cell width fits the widest ink in the set. Kerning is not applied.
 *
 * The advance table makes the output reusable for any face and charset: the
 * trusted atlas can be generated by the same tool with its own charset file.
 */
#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_OUTLINE_H
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

struct entry {
    unsigned long cp, base, mark; /* mark == 0: plain glyph */
};

struct bmp {
    int left, top, w, h; /* left: px right of pen; top: px above baseline */
    unsigned char *buf;
};

struct fonts {
    FT_Face prim, fall;
};

static int die(const char *what, unsigned long cp) {
    fprintf(stderr, "gen_atlas: %s U+%04lX\n", what, cp);
    return 1;
}

static int parse_charset(const char *path, struct entry **out, size_t *n) {
    FILE *f = fopen(path, "r");
    if (!f) {
        fprintf(stderr, "gen_atlas: cannot read %s\n", path);
        return 1;
    }
    size_t cap = 512;
    *out = malloc(cap * sizeof **out);
    *n = 0;
    char line[256];
    while (fgets(line, sizeof line, f)) {
        char *s = line;
        while (*s == ' ' || *s == '\t') s++;
        if (*s == '#' || *s == '\n' || *s == 0) continue;
        unsigned long a, b, m;
        struct entry e = {0, 0, 0};
        int k = 0;
        if (sscanf(s, "%lx=%lx+%lx", &a, &b, &m) == 3) {
            e.cp = a; e.base = b; e.mark = m;
            if (*n == cap) *out = realloc(*out, (cap *= 2) * sizeof **out);
            (*out)[(*n)++] = e;
        } else if (sscanf(s, "%lx-%lx", &a, &b) == 2) {
            for (unsigned long c = a; c <= b; c++) {
                if (*n == cap) *out = realloc(*out, (cap *= 2) * sizeof **out);
                e.cp = c; e.base = c;
                (*out)[(*n)++] = e;
            }
        } else if (sscanf(s, "%lx", &a) == 1) {
            e.cp = a; e.base = a;
            if (*n == cap) *out = realloc(*out, (cap *= 2) * sizeof **out);
            (*out)[(*n)++] = e;
        } else {
            fprintf(stderr, "gen_atlas: bad charset line: %s", s);
            return 1;
        }
        (void)k;
    }
    fclose(f);
    return 0;
}

static FT_Face pick(const struct fonts *fs, unsigned long cp) {
    if (FT_Get_Char_Index(fs->prim, cp)) return fs->prim;
    if (fs->fall && FT_Get_Char_Index(fs->fall, cp)) return fs->fall;
    return NULL;
}

/* Load `cp` from `face` at the face's current size and style it. */
static int load_styled(FT_Face face, unsigned long cp, FT_Pos embolden) {
    if (FT_Load_Char(face, cp, FT_LOAD_NO_BITMAP | FT_LOAD_TARGET_LIGHT)) return 1;
    if (embolden > 0) {
        FT_Outline_EmboldenXY(&face->glyph->outline, embolden, 0);
        FT_Outline_Translate(&face->glyph->outline, -embolden / 2, 0);
    }
    return 0;
}

static int render_cur(FT_Face face, struct bmp *b) {
    if (FT_Render_Glyph(face->glyph, FT_RENDER_MODE_LIGHT)) return 1;
    FT_Bitmap *s = &face->glyph->bitmap;
    b->left = face->glyph->bitmap_left;
    b->top = face->glyph->bitmap_top;
    b->w = (int)s->width;
    b->h = (int)s->rows;
    b->buf = calloc((size_t)(b->w * b->h) + 1, 1);
    for (int y = 0; y < b->h; y++) memcpy(b->buf + y * b->w, s->buffer + y * s->pitch, (size_t)b->w);
    return 0;
}

/* Union of two bitmaps, coverage combined with max(). Frees both. */
static void merge(struct bmp *a, struct bmp *m) {
    int l = a->left < m->left ? a->left : m->left;
    int t = a->top > m->top ? a->top : m->top;
    int r = a->left + a->w > m->left + m->w ? a->left + a->w : m->left + m->w;
    int bt = a->top - a->h < m->top - m->h ? a->top - a->h : m->top - m->h;
    struct bmp o = {l, t, r - l, t - bt, NULL};
    o.buf = calloc((size_t)(o.w * o.h) + 1, 1);
    const struct bmp *src[2] = {a, m};
    for (int i = 0; i < 2; i++) {
        for (int y = 0; y < src[i]->h; y++) {
            for (int x = 0; x < src[i]->w; x++) {
                unsigned char v = src[i]->buf[y * src[i]->w + x];
                unsigned char *p = &o.buf[(t - src[i]->top + y) * o.w + (src[i]->left - l + x)];
                if (v > *p) *p = v;
            }
        }
    }
    free(a->buf);
    free(m->buf);
    *a = o;
}

int main(int argc, char **argv) {
    const char *font = NULL, *fall = NULL, *charset = NULL, *out = NULL;
    double px = 0, embolden = 0;
    int scale = 1;
    for (int i = 1; i + 1 < argc; i += 2) {
        const char *k = argv[i], *v = argv[i + 1];
        if (!strcmp(k, "--font")) font = v;
        else if (!strcmp(k, "--fallback")) fall = v;
        else if (!strcmp(k, "--charset")) charset = v;
        else if (!strcmp(k, "--out")) out = v;
        else if (!strcmp(k, "--px")) px = atof(v);
        else if (!strcmp(k, "--scale")) scale = atoi(v);
        else if (!strcmp(k, "--embolden")) embolden = atof(v);
        else { fprintf(stderr, "gen_atlas: unknown option %s\n", k); return 2; }
    }
    if (!font || !charset || !out || px <= 0 || scale < 1) {
        fprintf(stderr, "usage: gen_atlas --font F --px N --scale S --charset C --out O "
                        "[--fallback G] [--embolden PX]\n");
        return 2;
    }
    struct entry *set;
    size_t n;
    if (parse_charset(charset, &set, &n)) return 1;

    FT_Library lib;
    struct fonts fs = {0, 0};
    if (FT_Init_FreeType(&lib) || FT_New_Face(lib, font, 0, &fs.prim)) {
        fprintf(stderr, "gen_atlas: cannot open %s\n", font);
        return 1;
    }
    if (fall && FT_New_Face(lib, fall, 0, &fs.fall)) {
        fprintf(stderr, "gen_atlas: cannot open %s\n", fall);
        return 1;
    }
    FT_F26Dot6 size = (FT_F26Dot6)lround(px * scale * 64.0);
    FT_Set_Char_Size(fs.prim, 0, size, 72, 72);
    if (fs.fall) FT_Set_Char_Size(fs.fall, 0, size, 72, 72);
    FT_Pos bold = embolden > 0 ? (FT_Pos)lround(embolden * scale * 64.0) : 0;

    double em = fs.prim->units_per_EM;
    int asc = (int)ceil(fs.prim->ascender / em * px * scale);
    int desc = (int)ceil(-fs.prim->descender / em * px * scale);

    unsigned short *adv = calloc(n, sizeof *adv);
    struct bmp *bm = calloc(n, sizeof *bm);
    int minl = 0, maxr = 0;
    for (size_t i = 0; i < n; i++) {
        const struct entry *e = &set[i];
        FT_Face f = pick(&fs, e->base);
        if (!f) return die("no glyph in any face for", e->base);
        /* Advance in design units, scaled to 1/64 logical px at --px. */
        if (FT_Load_Char(f, e->base, FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING)) return die("load failed", e->base);
        double a64 = f->glyph->metrics.horiAdvance * px * 64.0 / f->units_per_EM;
        adv[i] = (unsigned short)lround(a64);
        if (load_styled(f, e->base, bold) || render_cur(f, &bm[i])) return die("render failed", e->base);
        if (e->mark) {
            FT_BBox bb;
            FT_Outline_Get_CBox(&f->glyph->outline, &bb);
            if (!FT_Get_Char_Index(f, e->mark)) return die("face lacks mark", e->mark);
            if (load_styled(f, e->mark, bold)) return die("load failed", e->mark);
            FT_BBox mb;
            FT_Outline_Get_CBox(&f->glyph->outline, &mb);
            /* Marks are zero-advance overlays with ink left of the pen: put
             * the mark's ink centre on the base's advance-box centre. */
            FT_Pos dx = (FT_Pos)lround(a64 * scale / 2.0) - (mb.xMin + mb.xMax) / 2;
            FT_Pos gap = (FT_Pos)scale * 64;
            FT_Pos dy = mb.yMin < bb.yMax + gap ? bb.yMax + gap - mb.yMin : 0;
            FT_Outline_Translate(&f->glyph->outline, dx, dy);
            struct bmp mk;
            if (render_cur(f, &mk)) return die("render failed", e->mark);
            merge(&bm[i], &mk);
        }
        /* The line box is the face's own ascent/descent, grown to hold the
         * tallest and deepest glyph of the set (a cedilla, a ring). */
        if (bm[i].top > asc) asc = bm[i].top;
        if (bm[i].h - bm[i].top > desc) desc = bm[i].h - bm[i].top;
        if (bm[i].left < minl) minl = bm[i].left;
        if (bm[i].left + bm[i].w > maxr) maxr = bm[i].left + bm[i].w;
    }
    int ch = asc + desc;
    int margin = -minl + 1;
    int cw = margin + maxr + 1;
    if (cw > 255 || ch > 255 || margin > 255 || asc > 255) {
        fprintf(stderr, "gen_atlas: cell too large\n");
        return 1;
    }
    FILE *o = fopen(out, "wb");
    if (!o) {
        fprintf(stderr, "gen_atlas: cannot write %s\n", out);
        return 1;
    }
    unsigned char head[8] = {'H', 'U', 'D', '3', (unsigned char)cw, (unsigned char)ch,
                             (unsigned char)margin, (unsigned char)asc};
    fwrite(head, 1, 8, o);
    for (size_t i = 0; i < n; i++) {
        unsigned char b[2] = {adv[i] & 0xff, adv[i] >> 8};
        fwrite(b, 1, 2, o);
    }
    unsigned char *cell = malloc((size_t)(cw * ch));
    for (size_t i = 0; i < n; i++) {
        memset(cell, 0, (size_t)(cw * ch));
        for (int y = 0; y < bm[i].h; y++) {
            for (int x = 0; x < bm[i].w; x++) {
                int ty = asc - bm[i].top + y, tx = margin + bm[i].left + x;
                cell[ty * cw + tx] = bm[i].buf[y * bm[i].w + x];
            }
        }
        fwrite(cell, 1, (size_t)(cw * ch), o);
    }
    fclose(o);
    printf("%s: %zu glyphs, cell %dx%d margin %d ascent %d\n", out, n, cw, ch, margin, asc);
    return 0;
}
